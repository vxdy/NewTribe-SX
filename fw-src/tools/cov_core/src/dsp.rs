/// Predecoded instruction (built whenever an IRAM word is written). 8 bytes so that the hot part of the program stays in L1.
/// Bus field: bits 0-1 mode (0 none, 1 store, 2 load), 2-4 pointer, 5-7 modifier, 8-10 register, 11-13 part, 14 direction.
#[derive(Clone, Copy, Debug)]
struct Op(u64); // kind | hdt << 8 | (a | b << 3 | d << 6) << 16 | bus0 << 32 | bus1 << 48

impl Op {
    #[inline(always)] fn kind(self) -> u8 { self.0 as u8 }
    #[inline(always)] fn hdt(self) -> bool { (self.0 >> 8) & 1 != 0 }
    #[inline(always)] fn a(self) -> usize { ((self.0 >> 16) & 7) as usize }
    #[inline(always)] fn b(self) -> usize { ((self.0 >> 19) & 7) as usize }
    #[inline(always)] fn d(self) -> usize { ((self.0 >> 22) & 7) as usize }
    #[inline(always)] fn bus(self, i: u32) -> u16 { (self.0 >> (32 + 16 * i)) as u16 }
}

#[derive(Clone, Copy)]
struct Bus { mode: u8, n: u8, modi: u8, reg: u8, suf: u8, dir: u8 }

#[inline(always)]
fn bus_of(v: u16) -> Bus {
    Bus { mode: (v & 3) as u8, n: ((v >> 2) & 7) as u8, modi: ((v >> 5) & 7) as u8, reg: ((v >> 8) & 7) as u8, suf: ((v >> 11) & 7) as u8, dir: ((v >> 14) & 1) as u8 }
}

const K_GEN: u8 = 0;
const K_LD_DUAL: u8 = 64;
const K_LD_DIR: u8 = 65;
const K_LD_PTR: u8 = 66;

fn decode(w: u32) -> Op {
    let mk = |y: bool| -> u16 {
        let (sb, dxb, dpb, mb, rb, base) = if !y { (23, 17, 14, 11, 8, 0u32) } else { (20, 16, 6, 3, 0, 4) };
        let modi = (w >> mb) & 7;
        let dir = (w >> dxb) & 1;
        let mode = if modi == 0 || modi == 7 { 0 } else if dir == 1 { 2 } else { 1 };
        (mode | ((((w >> dpb) & 3) + base) << 2) | (modi << 5) | (((w >> rb) & 7) << 8) | (((w >> sb) & 7) << 11) | (dir << 14)) as u16
    };
    let hdt = (w >> 26) == 0b010010 && (w & 0x1FFFF) == 0x13820;
    let (mut kind, mut regs) = (K_GEN, 0u32);
    let rg = |a: u32, b: u32, d: u32| -> u32 { a | (b << 3) | (d << 6) };
    match w >> 28 {
        4 => match (w >> 26) & 3 { 3 => kind = K_LD_DUAL, 2 => kind = K_LD_DIR, 1 => kind = K_LD_PTR, _ => {} },
        6 => { kind = 48 + ((w >> 24) & 15) as u8; regs = rg((w >> 21) & 7, 0, (w >> 18) & 7); }
        7 => { kind = 32 + ((w >> 24) & 15) as u8; regs = rg((w >> 21) & 7, 0, (w >> 18) & 7); }
        8..=15 => { kind = 16 + ((w >> 24) & 15) as u8; regs = rg((w >> 28) & 7, (w >> 21) & 7, (w >> 18) & 7); }
        _ => {}
    }
    let op = Op(kind as u64 | (hdt as u64) << 8 | (regs as u64) << 16 | (mk(false) as u64) << 32 | (mk(true) as u64) << 48);
    op
}

#[inline(always)]
fn se40(v: i64) -> i64 { (v << 24) >> 24 }
#[inline(always)]
fn h16(r: i64) -> i32 { ((r >> 16) & 0xFFFF) as u16 as i16 as i32 }
fn l16(r: i64) -> u32 { (r & 0xFFFF) as u32 }

