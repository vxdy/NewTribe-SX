//! uPD77213 DSP core (uPD77016 instruction set) plus the peripherals the ESX-1 firmware uses.
//!
//! Instruction formats: "uPD77016 Family User's Manual - Instructions" (U13116E) appendix A, peripherals: "uPD77210 Family
//! User's Manual - Architecture" (U15807E). The opcode numbers are the table row order of those figures; the part mask of the
//! load/store "suf" field (1 = L, 2 = H, 4 = E, 6 = EH, 7 = whole register) was confirmed with the boot code. Everything is
//! executed without pipeline delays, one instruction per step.
//!
//! Speed: IRAM words are predecoded (`dec`, 8 bytes each) for the interpreter, and the factory firmware's DSP program is also
//! compiled ahead of time into Rust basic blocks (`dsp_aot.rs`, generated by `scratch/dspaot_gen.py`). The blocks call the same
//! helpers as the interpreter with constant operands, so they are bit-identical; they are only used while IRAM still holds exactly
//! the words they were generated from (`aot_on`, checked when the boot upload finishes and on every IRAM write) and fall back
//! to the interpreter for REP/LOOP/HALT/HDT instructions, interrupts, uncovered code and diagnostics (`ESX_DSP_NOAOT=1` disables them).
//! Regenerate after a different DSP program: record a session (`ESX_DSP_REC=1`, `scratch/dsprec2.py`), then
//! `ESX_DSP_NOAOT=1 DSP_REPLAY=rec.bin DSP_DUMP=dir cargo test --release replay -- --nocapture` and `python scratch/dspaot_gen.py dir/iram.bin dir/pcs.bin core/src/dsp_aot.rs`.
//! `cargo test --release lockstep|replay` (env `DSP_LOCKSTEP` / `DSP_REPLAY` = recording) compare AOT vs interpreter and print state hashes.

